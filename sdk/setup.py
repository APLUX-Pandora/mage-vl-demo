from pathlib import Path
import shutil
from setuptools import setup, Distribution, find_packages
from setuptools.command.build_py import build_py
from wheel.bdist_wheel import bdist_wheel

ROOT=Path(__file__).parent
FFMPEG_LIBRARIES = ('libmage_ffmpeg_pixel.so', 'libmage_ffmpeg_bitcost.so')


class Build(build_py):
    def run(self):
        assets=ROOT/'lib' if (ROOT/'lib/libmage_vl.so').is_file() else ROOT
        library=assets/'libmage_vl.so'
        if not library.is_file():
            raise RuntimeError('Missing qualified sdk/lib/libmage_vl.so; obtain the matching SDK delivery before installation')
        with library.open('rb') as stream:
            header=stream.read(20)
        if header[:6]!=b'\x7fELF\x02\x01' or int.from_bytes(header[18:20],'little')!=183:
            raise RuntimeError('The SDK library must be a 64-bit little-endian AArch64 ELF')
        # Input is generated by the fixed internal QNN common packaging tool.
        # This standard setuptools copy does not assemble another vendor closure.
        runtime=assets/'qnn248'
        required=[
            'inventory.json','manifest.json','sdk.yaml','QNN_NOTICE.txt','NOTICE.txt',
            'LICENSE.pdf','QNN_README.txt',
            'host/libQnnHtp.so','host/libQnnSystem.so',
            'host/libQnnHtpNetRunExtensions.so',
        ]
        for arch in (68,73,75,81):
            required += [f'host/libQnnHtpV{arch}Stub.so',
                         f'dsp/v{arch}/libQnnHtpV{arch}Skel.so']
        if any(not (runtime/name).is_file() for name in required):
            raise RuntimeError('Missing bundled QNN runtime resources; obtain the complete matching SDK delivery')
        if runtime.is_symlink() or any(path.is_symlink() or path.suffix in ('.h','.hpp','.cpp','.a')
               for path in runtime.rglob('*')):
            raise RuntimeError('QNN runtime delivery must contain regular runtime resources, not build inputs or symlinks')
        if any(not (assets/name).is_file() or (assets/name).is_symlink() for name in FFMPEG_LIBRARIES):
            raise RuntimeError('Missing bundled FFmpeg shared libraries; obtain the complete matching SDK delivery')
        super().run()
        dst=Path(self.build_lib)/'_mage_vl_native'
        if dst.exists():
            shutil.rmtree(dst)
        dst.mkdir()
        (dst/'__init__.py').write_text('"""Native Mage-VL runtime assets."""\n')
        shutil.copy2(library,dst/library.name)
        for name in FFMPEG_LIBRARIES:
            shutil.copy2(assets/name,dst/name)
        shutil.copytree(runtime,dst/'qnn248',dirs_exist_ok=True)
        shutil.copy2(ROOT/'python/LICENSE',dst/'PYTHON_LICENSE')
        ffmpeg=dst/'ffmpeg'
        ffmpeg.mkdir(exist_ok=True)
        for name in ('README.md', 'ffmpeg-source.tar.xz'):
            shutil.copy2(ROOT/'ffmpeg'/name,ffmpeg/name)
        for name in ('LICENSE','LICENSES','THIRD_PARTY_NOTICES.txt'):
            src=assets/name
            if src.is_dir():
                shutil.copytree(src,dst/name,dirs_exist_ok=True)
            elif src.is_file():
                shutil.copy2(src,dst/name)
class Binary(Distribution):
    def has_ext_modules(self):return True
class Wheel(bdist_wheel):
    def get_tag(self):return ('py3','none','linux_aarch64')
setup(packages=find_packages('python'), package_dir={'':'python'},
      cmdclass={'build_py':Build,'bdist_wheel':Wheel},distclass=Binary)
